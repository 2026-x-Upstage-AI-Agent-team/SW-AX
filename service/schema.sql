CREATE TABLE IF NOT EXISTS events(id TEXT PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS teams(
 id TEXT PRIMARY KEY, event TEXT NOT NULL REFERENCES events, name TEXT NOT NULL, rep TEXT NOT NULL DEFAULT '',
 roster TEXT NOT NULL DEFAULT '[]', email TEXT NOT NULL DEFAULT '', current TEXT, UNIQUE(event,name,rep));
CREATE TABLE IF NOT EXISTS batches(
 id TEXT PRIMARY KEY, event TEXT NOT NULL REFERENCES events, reqkey TEXT NOT NULL UNIQUE, digest TEXT NOT NULL,
 target TEXT REFERENCES teams, base TEXT, removed TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'preparing',
 created INTEGER NOT NULL, revision INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS files(
 id TEXT PRIMARY KEY, batch TEXT NOT NULL REFERENCES batches, pos INTEGER NOT NULL, name TEXT NOT NULL,
 ext TEXT NOT NULL, hash TEXT NOT NULL, size INTEGER NOT NULL, kind TEXT NOT NULL DEFAULT '?',
 state TEXT NOT NULL DEFAULT 'waiting', team TEXT REFERENCES teams, candidates TEXT NOT NULL DEFAULT '[]',
 excluded TEXT NOT NULL DEFAULT '[]', reason TEXT NOT NULL DEFAULT '', signals TEXT NOT NULL DEFAULT '{}',
 pages INTEGER NOT NULL DEFAULT 0, UNIQUE(batch,pos));
CREATE INDEX IF NOT EXISTS batch_files ON files(batch,pos);
CREATE TABLE IF NOT EXISTS submissions(
 id TEXT PRIMARY KEY, team TEXT NOT NULL REFERENCES teams, version INTEGER NOT NULL, files TEXT NOT NULL,
 digest TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'queued', job TEXT, started INTEGER, created INTEGER NOT NULL,
 updated INTEGER NOT NULL, attempts INTEGER NOT NULL DEFAULT 0, due REAL NOT NULL DEFAULT 0,
 error TEXT NOT NULL DEFAULT '', result TEXT, decision TEXT, note TEXT NOT NULL DEFAULT '',
 fields TEXT, revision INTEGER NOT NULL DEFAULT 0, UNIQUE(team,version));
CREATE TABLE IF NOT EXISTS batch_teams(batch TEXT REFERENCES batches, team TEXT REFERENCES teams,
 submission TEXT REFERENCES submissions, PRIMARY KEY(batch,team));
CREATE TABLE IF NOT EXISTS audit(id INTEGER PRIMARY KEY, ts INTEGER NOT NULL, subject TEXT NOT NULL,
 action TEXT NOT NULL, detail TEXT NOT NULL, actor TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS mail(id TEXT PRIMARY KEY, submission TEXT NOT NULL REFERENCES submissions,
 kind TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'draft', sent_to TEXT, created INTEGER NOT NULL,
 subject TEXT, body TEXT, revision INTEGER NOT NULL DEFAULT 0, approved_at INTEGER, sent_at INTEGER, UNIQUE(submission,kind));
CREATE TABLE IF NOT EXISTS reports(id TEXT PRIMARY KEY, event TEXT NOT NULL REFERENCES events,
 version INTEGER NOT NULL, selection TEXT NOT NULL, snapshot TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'queued',
 error TEXT NOT NULL DEFAULT '', created INTEGER NOT NULL, parent TEXT REFERENCES reports, UNIQUE(event,version));
